/*
 * Runs INSIDE the built backend image (piped to `node -` by pdf-smoke.sh).
 *
 * Renders a synthetic invoice through the compiled PdfService and a page
 * through PdfCacheService.getBrowser(), i.e. both browser launch paths of the
 * application. All data is fake; nothing touches a database or the network.
 *
 * stdout carries exactly one JSON line with the results (PDFs base64-encoded);
 * all log output is redirected to stderr so it cannot corrupt that line.
 */
const log = (...args) => process.stderr.write(args.join(' ') + '\n');
console.log = log;
console.info = log;
console.warn = log;

const INVOICE_NUMBER = process.env.SMOKE_INVOICE_NUMBER || 'SMOKE-INV-0001';

async function main() {
  // Compiled output inside the image; overridable to run against a host build.
  const distDir = process.env.SMOKE_DIST_DIR || '/app/dist';
  const { PdfService } = require(`${distDir}/core/services/pdf.service`);
  const { PdfCacheService } = require(`${distDir}/core/services/pdf-cache.service`);

  const invoice = {
    id: '00000000-0000-4000-8000-000000000001',
    number: INVOICE_NUMBER,
    type: 'invoice',
    status: 'sent',
    currency: 'USD',
    issueDate: new Date('2026-01-15T00:00:00Z'),
    dueDate: new Date('2026-02-14T00:00:00Z'),
    subtotal: 150,
    taxTotal: 15,
    discountTotal: 0,
    total: 165,
    notes: 'Synthetic invoice generated by the container smoke test.',
  };
  const client = {
    id: '00000000-0000-4000-8000-000000000002',
    name: 'Smoke Test Client Ltd',
    email: 'client@example.invalid',
    phone: '+10000000000',
    addressJson: { line1: '1 Example Street', city: 'Testville', country: 'Nowhere' },
  };
  const items = [
    { description: 'Synthetic widget', quantity: 2, unitPrice: 50, taxRate: 10, discountRate: 0, lineTotal: 110 },
    { description: 'Synthetic service hour', quantity: 1, unitPrice: 50, taxRate: 10, discountRate: 0, lineTotal: 55 },
  ];

  const servicePdf = await new PdfService().generateInvoicePdf({
    invoice,
    client,
    items,
    user: { companyName: 'Smoke Test Co' },
  });

  // PdfCacheService only needs CacheService for templates, not for getBrowser().
  const cacheService = new PdfCacheService({ get: async () => null, set: async () => undefined });
  const browser = await cacheService.getBrowser();
  let cachePdf;
  let browserVersion;
  let cacheExecutable;
  try {
    browserVersion = await browser.version();
    cacheExecutable = browser.process() ? browser.process().spawnfile : null;
    const page = await browser.newPage();
    await page.setContent(`<html><body><h1>Invoice ${INVOICE_NUMBER}</h1><p>PdfCacheService launch path</p></body></html>`);
    cachePdf = await page.pdf({ format: 'A4' });
  } finally {
    await cacheService.closeBrowser();
  }

  // stdout is a pipe: wait for the write to flush before exiting.
  const line =
    JSON.stringify({
      uid: process.getuid(),
      node: process.version,
      puppeteer: require('puppeteer/package.json').version,
      executablePathEnv: process.env.PUPPETEER_EXECUTABLE_PATH || null,
      cacheExecutable,
      browserVersion,
      servicePdf: Buffer.from(servicePdf).toString('base64'),
      cachePdf: Buffer.from(cachePdf).toString('base64'),
    }) + '\n';
  await new Promise((resolve, reject) => process.stdout.write(line, (err) => (err ? reject(err) : resolve())));
}

main().then(
  () => process.exit(0),
  (err) => {
    log('SMOKE FAILURE:', err && err.stack ? err.stack : String(err));
    process.exit(1);
  },
);
