import { Injectable } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository, LessThanOrEqual } from 'typeorm';
import { RecurringInvoice, RecurrenceFrequency } from '../entities/recurring-invoice.entity';
import { InvoicesService } from '../invoices/invoices.service';
import { CreateInvoiceDto } from '../invoices/dto/invoice.dto';
import { InvoiceItemDto } from '../invoices/dto/invoice-item.dto';
import { InvoiceType } from '../entities/invoice.entity';
import { addCalendarDays, addCalendarMonths, businessToday, toCalendarDate } from '../common/calendar-date';

@Injectable()
export class RecurringInvoicesService {
  constructor(
    @InjectRepository(RecurringInvoice)
    private recurringInvoiceRepository: Repository<RecurringInvoice>,
    private invoicesService: InvoicesService,
  ) {}

  /**
   * Process recurring invoices and generate invoices
   */
  async processRecurringInvoices(): Promise<{ generated: number; errors: string[] }> {
    // Today in the business timezone; all dates here are YYYY-MM-DD calendar
    // dates (common/calendar-date.ts), compared and stored without shifting
    const today = businessToday();

    // Find all active recurring invoices due today
    const dueRecurring = await this.recurringInvoiceRepository.find({
      where: {
        isActive: true,
        nextRunDate: LessThanOrEqual(today as unknown as Date),
      },
      relations: ['client'],
    });

    let generated = 0;
    const errors: string[] = [];

    for (const recurring of dueRecurring) {
      try {
        // Check if end date has passed
        if (recurring.endDate && toCalendarDate(recurring.endDate) < today) {
          recurring.isActive = false;
          await this.recurringInvoiceRepository.save(recurring);
          continue;
        }

        // Generate invoice from template
        // Note: number will be generated by InvoicesService.create() if not provided
        const invoiceDto: CreateInvoiceDto = {
          issueDate: today,
          dueDate: this.calculateDueDate(today, 30), // Default 30 days if not specified
          currency: recurring.currency,
          clientId: recurring.clientId,
          items: recurring.lineItemsJson.map((item) => ({
            description: item.description,
            quantity: item.quantity,
            unitPrice: item.unitPrice,
          })) as InvoiceItemDto[],
          notes: recurring.notes,
          // status: 'DRAFT', // Will be set by service - removed
          type: InvoiceType.INVOICE,
        };

        await this.invoicesService.create(invoiceDto, recurring.userId);

        // Update next run date
        recurring.nextRunDate = this.calculateNextRunDate(today, recurring.frequency, recurring.interval) as unknown as Date;
        recurring.invoicesGenerated++;
        await this.recurringInvoiceRepository.save(recurring);

        generated++;
      } catch (error) {
        errors.push(`Failed to generate invoice for recurring ${recurring.id}: ${error.message}`);
      }
    }

    return { generated, errors };
  }

  /**
   * Calculate next run date based on frequency
   */
  private calculateNextRunDate(currentDate: string, frequency: RecurrenceFrequency, interval: number): string {
    switch (frequency) {
      case RecurrenceFrequency.DAILY:
        return addCalendarDays(currentDate, interval);
      case RecurrenceFrequency.WEEKLY:
        return addCalendarDays(currentDate, 7 * interval);
      case RecurrenceFrequency.MONTHLY:
        return addCalendarMonths(currentDate, interval);
      case RecurrenceFrequency.QUARTERLY:
        return addCalendarMonths(currentDate, 3 * interval);
      case RecurrenceFrequency.YEARLY:
        return addCalendarMonths(currentDate, 12 * interval);
    }
    return currentDate;
  }

  /**
   * Calculate due date from issue date
   */
  private calculateDueDate(issueDate: string, days: number): string {
    return addCalendarDays(issueDate, days);
  }
}
